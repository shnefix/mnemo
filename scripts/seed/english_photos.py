#!/usr/bin/env python3
"""
Builds the photos of the English deck's "Name it (photos)" section from chosen Wikimedia Commons
images, and their credits.

Input: a JSON file mapping photo key → {"file": local image, "title", "page", "license", "artist"}
(the keys are the first column of EnglishPhotoContent.kt). Writes:

  composeApp/src/commonMain/composeResources/files/seed/en/<key>.webp   (longest side 720 px)
  composeApp/src/commonMain/kotlin/app/mnemo/data/seed/EnglishPhotoCredits.kt   (generated)
  CREDITS.md   (the photo section)

Only freely licensed photos (CC0, public domain, CC BY, CC BY-SA) are used, each credited on its
card. Usage: python3 scripts/seed/english_photos.py chosen.json
"""
import json
import os
import re
import sys

from PIL import Image, ImageOps

OUT_IMG = "composeApp/src/commonMain/composeResources/files/seed/en"
OUT_KT = "composeApp/src/commonMain/kotlin/app/mnemo/data/seed/EnglishPhotoCredits.kt"
CREDITS = "CREDITS.md"
LONG_SIDE = 720


def clean_artist(a):
    a = re.sub(r"\s+", " ", a or "").strip()
    a = re.sub(r"^User:", "", a)
    a = a.replace("Own work", "").strip(" ,;")
    if len(a) > 60:
        a = a[:57].rstrip() + "…"
    return a or "Unknown author"


def kt(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def main(path):
    chosen = json.load(open(path))
    os.makedirs(OUT_IMG, exist_ok=True)
    keep = set(chosen)
    for f in os.listdir(OUT_IMG):
        if f.endswith(".webp") and f[:-5] not in keep:
            os.remove(os.path.join(OUT_IMG, f))
    credits = {}
    for key, c in sorted(chosen.items()):
        img = ImageOps.exif_transpose(Image.open(c["file"])).convert("RGB")
        img.thumbnail((LONG_SIDE, LONG_SIDE), Image.LANCZOS)
        img.save(os.path.join(OUT_IMG, key + ".webp"), "WEBP", quality=74, method=6)
        credits[key] = dict(artist=clean_artist(c["artist"]), license=c["license"], page=c["page"], title=c["title"])

    with open(OUT_KT, "w") as f:
        f.write("package app.mnemo.data.seed\n\n")
        f.write("// Generated by scripts/seed/english_photos.py: do not edit by hand.\n\n")
        f.write("/** Who took each photo of the English deck's photo section, and its licence (all from Wikimedia Commons). */\n")
        f.write("internal object EnglishPhotoCredits {\n")
        f.write("    /** photo key → \"author · licence\" */\n")
        f.write("    val byKey: Map<String, String> =\n        mapOf(\n")
        for key, c in credits.items():
            f.write(f"            {kt(key)} to {kt(c['artist'] + ' · ' + c['license'])},\n")
        f.write("        )\n}\n")

    lines = [
        "# Credits",
        "",
        "## Photos in the English deck (\"Name it (photos)\")",
        "",
        "From [Wikimedia Commons](https://commons.wikimedia.org), resized. Each photo keeps its own licence;",
        "the author and licence are also shown on its card.",
        "",
        "| Photo | Author | Licence | Source |",
        "|---|---|---|---|",
    ]
    for key, c in credits.items():
        lines.append(f"| {key} | {c['artist'].replace('|', '/')} | {c['license']} | [{c['title']}]({c['page']}) |")
    open(CREDITS, "w").write("\n".join(lines) + "\n")
    total = sum(os.path.getsize(os.path.join(OUT_IMG, k + ".webp")) for k in credits)
    print(f"{len(credits)} photos, {total / 1e6:.1f} MB")


if __name__ == "__main__":
    main(sys.argv[1])
